        "اختر العلاقة الرياضية المناسبة للشروط الفيزيائية (ثبوت ضغط، ثبوت حجم، اتزان ديناميكي). تأكد من صحة النسب التكافؤية المولية.",
      commonPitfallWarning:
        "تحذير: لا تدمج بين قوانين الأنظمة المثالية والأنظمة الحقيقية دون التحقق من صلاحية الفرضيات.",
